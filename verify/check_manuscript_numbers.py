#!/usr/bin/env python3
"""Pin the manuscript's reliability figures to committed artefacts.

Run with ``python verify/check_manuscript_numbers.py`` (or ``make verify``).

Table 4 and section 4.6's pairwise judge kappa were computed once, live, and
for a long time existed in no file. They are now regenerated by
``pipeline/5_eval_reliability.py`` into results/agg/. This asserts the
committed CSVs still say what the manuscript says, so a rerun that shifts them
fails loudly instead of silently orphaning the prose.

Regenerate the inputs with ``make analysis``, or individually:
  python pipeline/5_eval_reliability.py
"""
import csv
import json
import sys
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGG = ROOT / "results" / "agg"

# Table 4, as printed: scope -> (no-match %, Fleiss kappa, Gwet AC1, Krippendorff alpha)
TABLE4 = {
    "all":     (32.0, 0.768, 0.783, 0.769),
    "weird":   (32.9, 0.761, 0.777, 0.762),
    "serbian": (31.1, 0.774, 0.789, 0.775),
}
# Section 4.6: the three lowest base-panel pairings, all involving the Gemini judge.
GEMINI_LOWEST = {
    "anthropic/claude-sonnet-5": 0.671,
    "openai/gpt-5.5": 0.684,
    "deepseek/deepseek-v4-pro": 0.695,
}
GEMINI = "google/gemini-3.1-pro-preview"

# Section 4.6 gold-assignment audit: scope -> (n, agreement %). Computed on the
# high-confidence subset (panel agreement weight >= 0.8) of the items where both
# annotators agreed; see reanalysis/build_human_assignment_input.py.
ASSIGNMENT = {"all": (33, 84.8), "weird": (15, 86.7), "serbian": (18, 83.3)}
REANALYSIS = ROOT / "results" / "reanalysis"


def fail(msg):
    """Report a mismatch and count it as one failure."""
    print(f"FAIL: {msg}")
    return 1


def check_table4():
    """Check Table 4's twelve reliability cells against the committed CSV."""
    bad = 0
    rows = {r["scope"]: r for r in csv.DictReader(open(AGG / "inter_judge_agreement.csv"))}
    for scope, (nm, k, ac1, alpha) in TABLE4.items():
        if scope not in rows:
            bad += fail(f"inter_judge_agreement.csv has no '{scope}' row")
            continue
        r = rows[scope]
        got = (round(float(r["no_match_rate"]) * 100, 1), round(float(r["fleiss_kappa"]), 3),
               round(float(r["gwet_ac1"]), 3), round(float(r["krippendorff_alpha"]), 3))
        if got != (nm, k, ac1, alpha):
            bad += fail(f"Table 4 row '{scope}': manuscript {(nm, k, ac1, alpha)}, csv {got}")
    # every perspective is one item; the 16 four-judge generations are why
    # n_verdicts is 5,184 and not 5,200
    if int(rows["all"]["n_items"]) != 1040:
        bad += fail(f"pooled n_items {rows['all']['n_items']}, manuscript says 1,040")
    if int(rows["all"]["n_verdicts"]) != 5184:
        bad += fail(f"pooled n_verdicts {rows['all']['n_verdicts']}, manuscript says 5,184")
    return bad


def _matrix(name):
    with open(AGG / name) as fh:
        rows = list(csv.reader(fh))
    judges = rows[0][1:]
    return {r[0]: dict(zip(judges, r[1:], strict=True)) for r in rows[1:]}


def check_pairwise():
    """Check section 4.6's pairwise-kappa claims against the committed CSVs."""
    bad = 0
    kappa = _matrix("pairwise_judge_kappa.csv")
    overlap = _matrix("pairwise_judge_overlap.csv")
    base = json.loads((ROOT / "results" / "adapted"
                       / "panels.json").read_text())["base_panel"]

    for other, expected in GEMINI_LOWEST.items():
        got = round(float(kappa[GEMINI][other]), 3)
        if got != expected:
            bad += fail(f"kappa(Gemini, {other}) is {got}, manuscript says {expected}")

    pairs = [(float(kappa[a][b]), int(float(overlap[a][b])))
             for a, b in combinations(sorted(base), 2)]
    ks = [k for k, _ in pairs]
    ns = [n for _, n in pairs]
    # "ranges from a Cohen's kappa of about 0.67 to about 0.85"
    if not (0.665 <= min(ks) < 0.675 and 0.845 <= max(ks) < 0.855):
        bad += fail(f"base-panel kappa range {min(ks):.3f}-{max(ks):.3f}, "
                    f"manuscript says about 0.67 to about 0.85")
    # "between 720 and 880 perspectives per pair"
    if (min(ns), max(ns)) != (720, 880):
        bad += fail(f"base-panel overlap {min(ns)}-{max(ns)}, manuscript says 720-880")
    # the three lowest pairings must all be Gemini's, or 4.6's claim is wrong
    lowest = sorted(combinations(sorted(base), 2), key=lambda p: float(kappa[p[0]][p[1]]))[:3]
    if not all(GEMINI in p for p in lowest):
        bad += fail(f"Gemini is not in all three lowest-agreement pairs: {lowest}")
    return bad


def check_assignment():
    """Check section 4.6's gold-assignment agreement against the committed CSV."""
    bad = 0
    path = REANALYSIS / "human_assignment_audit.csv"
    if not path.exists():
        return fail(f"{path} missing; run reanalysis/human_assignment_audit.py")
    with open(path) as fh:
        rows = list(csv.DictReader(fh))
    scopes = {"all": rows,
              "weird": [r for r in rows if r["arm"] == "WEIRD"],
              "serbian": [r for r in rows if r["arm"] == "SERBIAN"]}
    for scope, (n, pct) in ASSIGNMENT.items():
        sub = scopes[scope]
        agree = sum(r["agree"].strip().lower() == "true" for r in sub)
        got = (len(sub), round(100 * agree / len(sub), 1) if sub else 0.0)
        if got != (n, pct):
            bad += fail(f"gold assignment '{scope}': manuscript n={n} at {pct}%, "
                        f"csv n={got[0]} at {got[1]}%")
    return bad


if __name__ == "__main__":
    failures = check_table4() + check_pairwise() + check_assignment()
    if failures:
        print(f"\n{failures} manuscript claim(s) no longer match results/agg/")
        sys.exit(1)
    print("Table 4, section 4.6's pairwise kappa and the gold-assignment audit "
          "match their committed CSVs exactly.")
